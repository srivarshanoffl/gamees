def create_mask_from_bbox(img_size, bbox, feather=4):
    from PIL import ImageDraw
    mask = Image.new("L", img_size, 0)
    draw = ImageDraw.Draw(mask)
    draw.rectangle(bbox, fill=255)
    if feather > 0:
        mask = mask.filter(ImageFilter.GaussianBlur(feather))
    return mask

def cut_region(img, bbox, feather=3):
    mask = create_mask_from_bbox(img.size, bbox, feather)
    src_alpha = img.split()[3]
    combined_mask = Image.fromarray(np.minimum(np.array(mask), np.array(src_alpha)))
    out = Image.new("RGBA", img.size, (0, 0, 0, 0))
    out.paste(img, (0, 0), mask=combined_mask)
    return out

def rotate_and_place(part_img, angle, pivot, translate=(0, 0)):
    w, h = part_img.size
    pad = 250
    big = Image.new("RGBA", (w + pad * 2, h + pad * 2), (0, 0, 0, 0))
    big.paste(part_img, (pad, pad))
    center = (pivot[0] + pad, pivot[1] + pad)
    rotated = big.rotate(angle, resample=Image.BICUBIC, center=center)
    res = rotated.crop((pad - translate[0], pad - translate[1], pad - translate[0] + w, pad - translate[1] + h))
    return res

